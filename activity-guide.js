/*
 * Движение и активност — насоките в „Насоки“ (guidelines.html, секция data-guide="activity").
 *
 * Правилата са тук, в кода — като останалите насоки: целите идват от goal-focus.js (същите крачки
 * и групи като в „Напредък“), съветите — от признатите препоръки:
 *  - СЗО 2020 (Bull et al., Br J Sports Med 2020): 150–300 мин умерено или 75–150 мин интензивно
 *    седмично + силови ≥ 2 дни; 65+ — и баланс ≥ 3 дни; всяко движение се брои, седенето се прекъсва.
 *  - ACSM (Garber 2011; Progression models 2009; Schoenfeld 2017): силови 2–3 серии × 8–12 повторения,
 *    1–3 повторения „в резерв“; за мускулна маса ≥ 10 серии на мускулна група седмично; прогресия.
 *  - ADA 2016 (Colberg et al.): ходене след хранене; при инсулин — глюкоза преди, бърза захар подръка.
 *  - AHA 2023 (изометрични упражнения при хипертония), ACOG 2020 (бременност, след раждане),
 *    Royal Osteoporosis Society 2019 (сила + удар, без натоварено сгъване напред).
 * Числата за храната не са тук — те са в менюто. AI (plan_voice → plan.personalActivity) добавя
 * само 2–4 лични съвета за ежедневието на човека; без тях секцията е пълна.
 */
(function (global) {
    'use strict';

    var GF = global.NutriPlanGoalFocus || (typeof require === 'function' ? require('./goal-focus.js') : null);

    function list(v) { return Array.isArray(v) ? v : (v == null || v === '' ? [] : [v]); }
    function num(v) { var n = parseFloat(String(v == null ? '' : v).replace(',', '.')); return isFinite(n) ? n : null; }
    function fmt(n) { return String(Math.round(n)).replace(/\B(?=(\d{3})+(?!\d))/g, ' '); }

    /** Всичко, което клиентът е написал за здравето си — за разпознаване на състоянията. */
    function healthText(ud) {
        var parts = [];
        Object.keys(ud || {}).forEach(function (k) {
            if (/^(medicalConditions|healthConditions)/.test(k)) parts = parts.concat(list(ud[k]).map(String));
        });
        return parts.join(' ').toLowerCase();
    }

    var SPORT_DAYS = { 'Никаква': 0, 'Ниска': 1.5, 'Средна': 3, 'Висока': 6, 'Много висока': 6 };
    function sportDaysOf(label) {
        var s = String(label || '');
        for (var k in SPORT_DAYS) if (s.indexOf(k) === 0) return SPORT_DAYS[k];
        return 0;
    }

    /** Контекстът на човека за движението. */
    function contextOf(ud) {
        ud = ud || {};
        var p = GF ? GF.profileOf(ud) : { group: 'health', stepTarget: 8000, bp: false, glucose: false };
        var h = healthText(ud);
        var kg = num(ud.weight), cm = num(ud.height), age = num(ud.age);
        var bmi = kg && cm ? kg / Math.pow(cm / 100, 2) : null;
        var status = String(ud.postpartumStatus || '');
        var postpartum = ud.clinicalProtocol === 'postpartum_lactation' || /след бременност/.test(h);
        var types = list(ud.sportTypes).map(String);
        return {
            p: p,
            group: p.group,
            age: age,
            bmi: bmi,
            female: ud.gender === 'Жена',
            daily: /^Ниск/.test(String(ud.dailyActivityLevel || '')) ? 1 : /^Висок/.test(String(ud.dailyActivityLevel || '')) ? 3 : 2,
            sportDays: sportDaysOf(ud.sportActivity),
            minutes: String(ud.sportSessionMinutes || ''),
            strength: types.some(function (t) { return /^Силови/.test(t); }),
            cardio: types.some(function (t) { return /^(Кардио|Бързо ходене|Отборен|Бойни|Групови)/.test(t); }),
            mind: types.some(function (t) { return /^Йога/.test(t); }),
            hard: types.some(function (t) { return /^(Бойни|Групови|Отборен)/.test(t); }),
            pregnant: postpartum && /^Бременна/.test(status),
            lactating: postpartum && /^Кърмя/.test(status),
            postpartum: postpartum && !/^Бременна/.test(status),
            bp: p.bp || /хипертон|кръвно/.test(h),
            glucose: p.glucose || /диабет|инсулин|спкя|поликист/.test(h),
            insulin: /инсулин(ова)? терапия|на инсулин|инжекц|тип 1|1 тип/.test(h),
            // Сърцето — по конкретното състояние; само „Сърдечно-съдови“ с хипертония не е сърдечно заболяване.
            heart: /сърдечна недостат|сърце|аритми|предсърдно|инфаркт|стенокард|исхеми|атероскл|коронар|клап|стент|байпас|друго сърдечно/.test(h) ||
                (/сърдечно-съдов/.test(h) && !/хипертон|кръвно|варикоз/.test(h)),
            osteo: /остеопор|остеопен/.test(h),
            joints: /став|артр|артроз|колян|гръб|кръст|дискова|херни|ревмат|фибромиалг|мускулно-скелет|подагр/.test(h),
            anemia: /анеми|желязо/.test(h),
            reflux: /рефлукс|киселин/.test(h),
            sleep: /сън|безсъни/.test(h) || num(ud.sleepHours) != null && num(ud.sleepHours) < 6,
            mood: /депрес|тревож/.test(h) || p.stress,
            meno: /менопауз/.test(h),
            autoimmune: /автоимун|хашимото|щитовид/.test(h)
        };
    }

    /** Седмичните цели: крачки (като в „Напредък“), силови дни, умерено движение. */
    function targetsOf(c) {
        var g = c.group;
        var strength = c.pregnant ? null : g === 'gain' ? '3–4' : g === 'tone' ? '3' : g === 'lose' ? '2–3' : g === 'lose_soft' ? '1–2' : '2';
        var cardio = g === 'lose' ? '150–300' : g === 'gain' ? '90–150' : '150';
        var t = [{ icon: 'fa-person-walking', value: fmt(c.p.stepTarget || 8000), label: 'крачки на ден' }];
        if (strength) t.push({ icon: 'fa-dumbbell', value: strength, label: 'силови тренировки седмично' });
        t.push({ icon: 'fa-heart-pulse', value: cardio, label: 'мин умерено движение седмично' });
        if (c.age != null && c.age >= 65) t.push({ icon: 'fa-scale-balanced', value: '3', label: 'дни упражнения за баланс' });
        return t;
    }

    var FOCUS = {
        lose: [
            'Основата е ежедневното ходене — то гори най-много за седмицата и не усилва глада.',
            'Силовите пазят мускула, докато сваляш. Без тях част от свалените килограми са мускул, а не мазнини.',
            'Кардиото е добавка, не наказание: умерено темпо, при което можеш да говориш.'
        ],
        lose_soft: [
            'Сега водещото е възстановяването: ходене всеки ден и упражнения за тазовото дъно.',
            'Силовите се връщат постепенно — леки, с контрол, без задържане на дъха.',
            'Умората е сигнал, не слабост: в лошата нощ разходката е достатъчна.'
        ],
        gain: [
            'Мускулът расте от силовите тренировки с постепенно увеличаване на тежестта, а храната и сънят му дават материала.',
            'Всяка мускулна група — поне два пъти седмично, с последните повторения трудни, но с чиста техника.',
            'Кардиото остава за сърцето — леко и кратко, за да не отнема от възстановяването.'
        ],
        tone: [
            'Стягането е мускул, който се вижда: силовите за цялото тяло са в центъра.',
            'Крачките и умереното кардио свалят мазнините отгоре — без драстичен дефицит.',
            'Най-голямата разлика правят постоянството и постепенно по-тежките серии, не новите упражнения.'
        ],
        health: [
            'Целта е редовното движение, а не изтощението: малко всеки ден е повече от много веднъж.',
            'Силовите два пъти седмично пазят мускулите, костите и кръвната захар с възрастта.',
            'Седенето се прекъсва — всеки час по няколко минути на крак.'
        ]
    };

    /** Началната седмица — според това, което човекът прави сега. */
    function weekPlan(c) {
        var out = [];
        if (c.pregnant) {
            return [
                'Ходене, плуване или колело на място — по 20–30 мин в повечето дни, с темпо, при което говориш свободно.',
                'Леки силови с ластик или собствено тегло 2 пъти седмично; без упражнения по гръб за дълго след първия триместър.',
                'Упражнения за тазовото дъно — всеки ден, по няколко минути.'
            ];
        }
        if (c.postpartum) {
            out.push('Първите седмици: ходене всеки ден, постепенно до 30 мин; упражнения за тазовото дъно и дишане с корема.');
            out.push('След прегледа при лекаря (около 6-та седмица): леки силови за цялото тяло 2 пъти седмично.');
            out.push('Бягане, скокове и коремни преси — чак когато тазовото дъно и коремът са готови (обикновено след 12-та седмица, по преценка на специалист).');
            return out;
        }
        if (c.sportDays === 0) {
            out.push('Седмици 1–2: ходене по 20–30 мин в 5 дни + 2 кратки тренировки по 20 мин със собствено тегло.');
            out.push('Седмици 3–4: ходенето става 30–40 мин или по-бързо; тренировките — 3 серии вместо 2.');
            out.push('От втория месец: силовите стават 2–3 пъти седмично с ластик или дъмбели, ходенето остава.');
            return out;
        }
        if (!c.strength && c.group !== 'lose_soft') {
            out.push(c.mind
                ? 'Йогата и пилатесът са добра основа. Добави 2 силови тренировки седмично — с тежест, която да е трудна в края на серията.'
                : 'Добави 2 силови тренировки седмично към това, което правиш — те пазят мускула и правят кардиото по-ефективно.');
        }
        if (c.strength && !c.cardio && c.group !== 'gain') {
            out.push('Към силовите добави 2 пъти седмично по 20–30 мин умерено кардио — бързо ходене, колело или плуване.');
        }
        if (c.strength && c.group === 'gain') {
            out.push('Разпредели тренировките така, че всяка мускулна група да се натоварва 2 пъти седмично (цяло тяло или горна/долна част).');
        }
        if (c.sportDays >= 5) out.push('При 5 и повече тренировки — поне един ден седмично е лек (разходка, стречинг) или пълна почивка.');
        if (c.hard) out.push('Отборните, бойните и груповите тренировки са интензивни — броят се за кардиото; силовите остават отделно.');
        if (!out.length) out.push('Тренировките ти покриват основното. Пази редовността и увеличавай постепенно — серии, тежест или темпо.');
        return out;
    }

    /** Как да тренираш правилно — практика, не теория. */
    function howTo(c) {
        var out = [
            'Загрявка 5–10 мин: бързо ходене, кръгове с ръцете и ханша, няколко леки клека.',
            'Умерено темпо значи: можеш да говориш, но не и да пееш. Интензивно — говориш с прекъсвания.'
        ];
        if (!c.pregnant) {
            out.push(c.group === 'gain'
                ? 'Силови: 3–4 серии по 6–12 повторения; спираш, когато остават 1–2 повторения до отказ. Когато минеш горната граница — добави тежест.'
                : 'Силови: 2–3 серии по 8–12 повторения на упражнение. Последните 2 повторения трябва да са трудни, но с чиста техника.');
            out.push('Основните движения покриват цялото тяло: клек, напад, мост за седалището, гребане, избутване (лицеви опори от пейка или стена), планк.');
            out.push('Увеличавай постепенно — с около 10% седмично (минути, серии или тежест), не всичко наведнъж.');
        }
        out.push('Една и съща мускулна група — с поне ден почивка между силовите. Сънят е част от тренировката.');
        return out;
    }

    /** Ежедневното движение (извън тренировките) — по това колко се движи през деня. */
    function daily(c) {
        var out = [];
        if (c.daily === 1) {
            out.push('На всеки 30–45 мин седене — 2–3 мин на крак: до прозореца, за вода, по стълбите.');
            out.push('Телефонните разговори — прав или в движение.');
        }
        out.push('10–15 мин разходка след основните хранения — най-лесните крачки за деня и по-спокойна кръвна захар.');
        out.push('Стълби вместо асансьор, слизане спирка по-рано, паркиране по-далеч — всичко се брои.');
        if (c.daily === 3) out.push('Денят ти е активен — крачките идват сами; пази силовите, тях работата не ги замества.');
        return out;
    }

    /** На какво да внимаваш — по здравето. Общите сигнали за спиране са винаги. */
    function safety(c) {
        var out = [];
        if (c.pregnant) out.push('Без контактни спортове, падания, горещи зали и гмуркане. Спри при кървене, контракции, изтичане на течност, замайване или болка — и се обади на лекаря.');
        if (c.lactating) out.push('Кърми или изцеди преди тренировка и пий вода — при кърмене нуждата е по-голяма.');
        if (c.postpartum) out.push('Тежест или натиск надолу в таза, изпускане на урина или „купол“ по средата на корема при напъване — сигнал да намалиш и да се обърнеш към специалист по тазово дъно.');
        if (c.heart) out.push('При сърдечно-съдово заболяване — натоварването се съгласува с кардиолога. Без резки максимални усилия; загрявката и разпускането са по-дълги.');
        if (c.bp) out.push('Кръвно: не задържай дъха — издишвай при усилието. Без максимални тежести. Редовното умерено кардио и изометричните упражнения (стенен клек, планк) помагат за налягането.');
        if (c.glucose) out.push('Кръвна захар: разходката след хранене е най-силният ти навик. Силовите подобряват чувствителността към инсулин.');
        if (c.insulin) out.push('На инсулин: измери глюкозата преди тренировка и носи бърза захар (сок, глюкозни таблетки). Не тренирай интензивно на празен стомах.');
        if (c.osteo) out.push('Кости: силовите и лекият удар (ходене, стълби) ги укрепват. Без сгъване напред с тежест и рязко усукване на гърба.');
        if (c.joints) out.push('Стави и гръб: избирай движения без удар — плуване, колело, елипсовиден тренажор, ходене. Лека болка до 3 от 10, която минава до следващия ден, е допустима; остра или нарастваща — спри.');
        if (c.bmi != null && c.bmi >= 35 && !c.joints) out.push('Започни с движения без удар (ходене, колело, вода) и кратки отрязъци по 10 мин — събират се за деня.');
        if (c.age != null && c.age >= 65) out.push('Баланс 3 пъти седмично: стоене на един крак до опора, ходене пета-пръсти, ставане от стол без ръце.');
        if (c.anemia) out.push('Докато желязото се възстановява — умерено натоварване; ако се задъхваш или се виеш на свят, съкрати.');
        if (c.reflux) out.push('Рефлукс: тренирай поне 2 часа след хранене; без коремни преси и наведени пози веднага след ядене.');
        if (c.autoimmune) out.push('При автоимунно състояние — по енергията за деня: в лош ден разходка и стречинг, в добър — пълната тренировка.');
        if (c.meno) out.push('Менопауза: силовите 2–3 пъти седмично и лекият удар пазят костите и мускула, който сега се губи по-бързо.');
        if (c.sleep) out.push('Сън: интензивните тренировки — поне 3 часа преди лягане. Сутрешна разходка на дневна светлина помага на съня.');
        if (c.mood) out.push('Настроение: движението навън в повечето дни помага реално — дори 10 минути се броят.');
        out.push('Спри и потърси лекар при болка в гърдите, силен задух, замайване, сърцебиене или внезапна слабост.');
        return out;
    }

    /** Храна и движение — без числа (те са в менюто). */
    function fuel(c) {
        var out = [];
        if (c.group === 'gain' || c.group === 'tone' || c.strength) out.push('След силова тренировка — хранене с белтък в следващите 1–2 часа (то вече е в менюто ти).');
        out.push('Вода преди, по време и след тренировка — при потене и в жега повече.');
        if (c.group === 'lose') out.push('Не „награждавай“ тренировката с храна — разходът ѝ вече е сметнат в плана.');
        if (c.glucose || c.insulin) out.push('Тренировката след хранене (а не на гладно) пази кръвната захар по-стабилна.');
        return out;
    }

    /**
     * Насоките за движение.
     * @param {object} userData  отговорите от въпросника (localStorage userData)
     * @param {object} [plan]    планът (за личните съвети от AI — plan.personalActivity)
     */
    function build(userData, plan) {
        var c = contextOf(userData);
        var personal = list(plan && plan.personalActivity).map(String).filter(Boolean).slice(0, 4);
        var sections = [];
        if (personal.length) sections.push({ key: 'personal', title: 'За теб', items: personal });
        sections.push({ key: 'focus', title: 'Защо и какво', items: FOCUS[c.group] || FOCUS.health });
        sections.push({ key: 'week', title: c.pregnant || c.postpartum ? 'Седмицата ти сега' : 'Как да започнеш', items: weekPlan(c) });
        sections.push({ key: 'how', title: 'Как да тренираш правилно', items: howTo(c) });
        sections.push({ key: 'daily', title: 'Движение през деня', items: daily(c) });
        sections.push({ key: 'fuel', title: 'Храна и движение', items: fuel(c) });
        sections.push({ key: 'safety', title: 'На какво да внимаваш', items: safety(c) });
        return { v: 1, group: c.group, targets: targetsOf(c), sections: sections, clearance: c.pregnant || c.heart || c.insulin };
    }

    var api = { build: build, contextOf: contextOf };
    global.NutriPlanActivityGuide = api;
    if (typeof module !== 'undefined' && module.exports) module.exports = api;
}(typeof window !== 'undefined' ? window : globalThis));
